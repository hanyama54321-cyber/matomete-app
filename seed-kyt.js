// db: firebase.firestore() のインスタンス。log: ログ出力用コールバック(引数1つ、文字列)
async function seedKyt(db, log) {
  log('=== KYTシナリオ投入 開始(7件・冪等) ===');
  const baseMillis = Date.now();
  for (let i = 0; i < KYT_SAMPLE.length; i++) {
    const s = KYT_SAMPLE[i];
    const ts = firebase.firestore.Timestamp.fromMillis(baseMillis + i * 1000);
    await db.collection('kyt').doc(s.id).set({
      title: s.title,
      desc: s.desc,
      img: s.img,
      difficulty: s.difficulty,
      hints: s.hints,
      createdAt: ts,
      updatedAt: ts,
    });
    log(`✓ kyt/${s.id} → ${s.title}`);
  }
  log(`=== 完了(${KYT_SAMPLE.length}件)。再実行しても同じ内容に上書きされるだけです ===`);
}
